import type { AnalysisResult } from "../types";

export function downloadReport(result: AnalysisResult, fileName: string) {
  const lines = [
    "CANAL WATCH — BLOCKAGE DETECTION REPORT",
    "========================================",
    "",
    `Image file:            ${fileName}`,
    `Image ID:               ${result.imageId}`,
    `Analyzed at:            ${new Date(result.analyzedAt).toLocaleString()}`,
    "",
    `Blockage status:        ${result.blockageDetected ? "DETECTED" : "NOT DETECTED"}`,
    `Confidence score:       ${result.confidence.toFixed(1)}%`,
    `Blockage type:          ${result.blockageType}`,
    `Severity:               ${result.severity}`,
    `Affected channel area:  ${result.affectedAreaPercent.toFixed(1)}%`,
    "",
    ...(result.job
      ? [
          `Job ID:                 ${result.job.job_id}`,
          `Total reaches:          ${result.job.summary.total_reaches}`,
          `Clear / partial / full: ${result.job.summary.clear} / ${result.job.summary.partial} / ${result.job.summary.full ?? result.job.summary.blocked ?? 0}`,
          `Silt low / med / high:  ${result.job.summary.silt_low} / ${result.job.summary.silt_medium} / ${result.job.summary.silt_high}`,
          "",
        ]
      : []),
    "AI RECOMMENDATIONS",
    "-------------------",
    ...result.recommendations.map((r, i) => `${i + 1}. ${r}`),
    "",
    "Generated by Canal Watch — AI-Powered Canal Blockage Detection System",
  ];

  const blob = new Blob([lines.join("\n")], { type: "text/plain;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `canal-watch-report-${result.imageId}.txt`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
